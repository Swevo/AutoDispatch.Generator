    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
            ctx.AddSource("AutoDispatch.Attributes.g.cs", AttributeSource));

        var handlers = MakeHandlerProvider(context, "AutoDispatch.HandlerAttribute")
            .Collect()
            .Combine(MakeHandlerProvider(context, "AutoDispatch.CommandHandlerAttribute").Collect())
            .Combine(MakeHandlerProvider(context, "AutoDispatch.QueryHandlerAttribute").Collect());

        var behaviors = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.BehaviorAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformBehavior(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var streamBehaviors = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.StreamBehaviorAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformStreamBehavior(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var notificationHandlers = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.NotificationHandlerAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformNotificationHandler(ctx, ct))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!)
            .Collect();

        var streamHandlers = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.StreamHandlerAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformStreamHandler(ctx, ct))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!)
            .Collect();

        var exceptionHandlers = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.ExceptionHandlerAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformExceptionHandler(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var exceptionActions = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.ExceptionActionAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformExceptionAction(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var exceptionMiddleware = exceptionHandlers.Combine(exceptionActions);

        var preProcessors = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.PreProcessorAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformPreProcessor(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var postProcessors = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoDispatch.PostProcessorAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformPostProcessor(ctx, ct))
            .Where(static b => b is not null)
            .Select(static (b, _) => b!)
            .Collect();

        var processors = preProcessors.Combine(postProcessors);

        var allInputs = handlers.Combine(behaviors).Combine(notificationHandlers).Combine(streamHandlers).Combine(streamBehaviors).Combine(exceptionMiddleware).Combine(processors).Combine(context.CompilationProvider);

        context.RegisterSourceOutput(allInputs, static (ctx, tuple) =>
        {
            var (((((((handlersTuple, behaviorList), notificationList), streamList), streamBehaviorList), exceptionMiddlewareTuple), processorsTuple), compilation) = tuple;
            var ((h1, h2), h3) = handlersTuple;
            var (exceptionHandlerList, exceptionActionList) = exceptionMiddlewareTuple;
            var (preProcessorList, postProcessorList) = processorsTuple;
            Generate(ctx, h1.AddRange(h2).AddRange(h3), behaviorList, notificationList, streamList, streamBehaviorList, exceptionHandlerList, exceptionActionList, preProcessorList, postProcessorList, compilation);
        });
    }

    private static IncrementalValuesProvider<HandlerInfo> MakeHandlerProvider(
        IncrementalGeneratorInitializationContext context,
        string attributeFqn) =>
        context.SyntaxProvider
            .ForAttributeWithMetadataName(
                attributeFqn,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => TransformHandler(ctx, ct))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!);

    private static HandlerInfo? TransformHandler(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
        {
            return null;
        }

        var info = new HandlerInfo
        {
            HandlerTypeFqn = ToFullyQualified(typeSymbol),
            HandlerDisplayName = typeSymbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            Location = typeSymbol.Locations.FirstOrDefault() ?? Location.None,
            LifetimeMethod = ReadLifetimeMethod(context.Attributes)
        };

        var cancellationTokenType = context.SemanticModel.Compilation.GetTypeByMetadataName("System.Threading.CancellationToken");

        foreach (var member in typeSymbol.GetMembers().OfType<IMethodSymbol>())
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (member.MethodKind != MethodKind.Ordinary ||
                member.IsStatic ||
                member.DeclaredAccessibility != Accessibility.Public)
            {
                continue;
            }

            if (member.Name == "Handle")
            {
                TryAddSyncMethod(info, member);
                continue;
            }

            if (member.Name == "HandleAsync")
            {
                TryAddAsyncMethod(info, member, cancellationTokenType);
            }
        }

        return info;
    }

    private static NotificationHandlerInfo? TransformNotificationHandler(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
        {
            return null;
        }

        var info = new NotificationHandlerInfo
        {
            HandlerTypeFqn = ToFullyQualified(typeSymbol),
            HandlerDisplayName = typeSymbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            Location = typeSymbol.Locations.FirstOrDefault() ?? Location.None,
            LifetimeMethod = ReadLifetimeMethod(context.Attributes)
        };

        var cancellationTokenType = context.SemanticModel.Compilation.GetTypeByMetadataName("System.Threading.CancellationToken");

        foreach (var member in typeSymbol.GetMembers("HandleAsync").OfType<IMethodSymbol>())
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (member.MethodKind != MethodKind.Ordinary ||
                member.IsStatic ||
                member.DeclaredAccessibility != Accessibility.Public)
            {
                continue;
            }

            TryAddNotificationMethod(info, member, cancellationTokenType);
        }

        return info;
    }

    private static void TryAddNotificationMethod(
        NotificationHandlerInfo handler,
        IMethodSymbol method,
        INamedTypeSymbol? cancellationTokenType)
    {
        if (method.Parameters.Length is < 1 or > 2)
        {
            return;
        }

        // Notification handlers return Task only — they publish, they don't produce a result.
        if (method.ReturnType.ToDisplayString() != "System.Threading.Tasks.Task")
        {
            return;
        }

        if (method.Parameters.Length == 2 &&
            (cancellationTokenType is null ||
             !SymbolEqualityComparer.Default.Equals(method.Parameters[1].Type, cancellationTokenType)))
        {
            return;
        }

        handler.Methods.Add(new NotificationMethodInfo
        {
            NotificationTypeFqn = ToFullyQualified(method.Parameters[0].Type),
            NotificationDisplayName = method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            HandlerTypeFqn = handler.HandlerTypeFqn,
            HandlerDisplayName = handler.HandlerDisplayName,
            HasCancellationTokenParameter = method.Parameters.Length == 2,
            ParallelPublish = method.Parameters[0].Type.GetAttributes().Any(static a =>
                a.AttributeClass?.ToDisplayString() == "AutoDispatch.ParallelPublishAttribute"),
            Location = method.Locations.FirstOrDefault() ?? handler.Location,
            DocCommentXml = GetDocCommentXml(method)
        });
    }

    private static StreamHandlerInfo? TransformStreamHandler(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
        {
            return null;
        }

        var info = new StreamHandlerInfo
        {
            HandlerTypeFqn = ToFullyQualified(typeSymbol),
            HandlerDisplayName = typeSymbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            Location = typeSymbol.Locations.FirstOrDefault() ?? Location.None,
            LifetimeMethod = ReadLifetimeMethod(context.Attributes)
        };

        var cancellationTokenType = context.SemanticModel.Compilation.GetTypeByMetadataName("System.Threading.CancellationToken");

        foreach (var member in typeSymbol.GetMembers("HandleAsync").OfType<IMethodSymbol>())
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (member.MethodKind != MethodKind.Ordinary ||
                member.IsStatic ||
                member.DeclaredAccessibility != Accessibility.Public)
            {
                continue;
            }

            TryAddStreamMethod(info, member, cancellationTokenType);
        }

        return info;
    }

    private static void TryAddStreamMethod(
        StreamHandlerInfo handler,
        IMethodSymbol method,
        INamedTypeSymbol? cancellationTokenType)
    {
        if (method.Parameters.Length is < 1 or > 2)
        {
            return;
        }

        var resultTypeFqn = GetAsyncEnumerableResultTypeFqn(method.ReturnType);
        if (resultTypeFqn is null)
        {
            return;
        }

        if (method.Parameters.Length == 2 &&
            (cancellationTokenType is null ||
             !SymbolEqualityComparer.Default.Equals(method.Parameters[1].Type, cancellationTokenType)))
        {
            return;
        }

        handler.Methods.Add(new StreamMethodInfo
        {
            QueryTypeFqn = ToFullyQualified(method.Parameters[0].Type),
            QueryDisplayName = method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            HandlerTypeFqn = handler.HandlerTypeFqn,
            HandlerDisplayName = handler.HandlerDisplayName,
            ResultTypeFqn = resultTypeFqn,
            HasCancellationTokenParameter = method.Parameters.Length == 2,
            Location = method.Locations.FirstOrDefault() ?? handler.Location,
            DocCommentXml = GetDocCommentXml(method)
        });
    }

    private static void TryAddSyncMethod(HandlerInfo handler, IMethodSymbol method)
    {
        if (method.Parameters.Length != 1 || IsTaskLike(method.ReturnType))
        {
            return;
        }

        handler.Methods.Add(new DispatchMethodInfo
        {
            CommandTypeFqn = ToFullyQualified(method.Parameters[0].Type),
            CommandDisplayName = method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            HandlerTypeFqn = handler.HandlerTypeFqn,
            HandlerDisplayName = handler.HandlerDisplayName,
            ReturnTypeFqn = method.ReturnsVoid ? "void" : ToFullyQualified(method.ReturnType),
            MethodName = "Handle",
            IsAsync = false,
            HasCancellationTokenParameter = false,
            Location = method.Locations.FirstOrDefault() ?? handler.Location,
            DocCommentXml = GetDocCommentXml(method)
        });
    }

    private static void TryAddAsyncMethod(
        HandlerInfo handler,
        IMethodSymbol method,
        INamedTypeSymbol? cancellationTokenType)
    {
        if (method.Parameters.Length is < 1 or > 2)
        {
            return;
        }

        if (!IsTaskLike(method.ReturnType))
        {
            return;
        }

        if (method.Parameters.Length == 2 &&
            (cancellationTokenType is null ||
             !SymbolEqualityComparer.Default.Equals(method.Parameters[1].Type, cancellationTokenType)))
        {
            return;
        }

        handler.Methods.Add(new DispatchMethodInfo
        {
            CommandTypeFqn = ToFullyQualified(method.Parameters[0].Type),
            CommandDisplayName = method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
            HandlerTypeFqn = handler.HandlerTypeFqn,
            HandlerDisplayName = handler.HandlerDisplayName,
            ReturnTypeFqn = ToFullyQualified(method.ReturnType),
            MethodName = "HandleAsync",
            IsAsync = true,
            HasCancellationTokenParameter = method.Parameters.Length == 2,
            AsyncResultTypeFqn = GetAsyncResultTypeFqn(method.ReturnType),
            Location = method.Locations.FirstOrDefault() ?? handler.Location,
            DocCommentXml = GetDocCommentXml(method)
        });
    }

    /// <summary>
    /// Reads the handler method's own XML doc comment (if any) so it can be forwarded onto
    /// the generated <c>IDispatcher</c> member, giving callers real IntelliSense instead of
    /// undocumented generated code.
    /// </summary>
    private static string? GetDocCommentXml(IMethodSymbol method)
    {
        var xml = method.GetDocumentationCommentXml(expandIncludes: true);
        return string.IsNullOrWhiteSpace(xml) ? null : xml;
    }

    /// <summary>
    /// Converts a symbol's raw `GetDocumentationCommentXml()` output (a single
    /// &lt;member&gt;...&lt;/member&gt; fragment) into indented `///` doc-comment lines
    /// suitable for emission above a generated member.
    /// </summary>
    private static void AppendDocComment(StringBuilder sb, string? docCommentXml, string indent)
    {
        if (string.IsNullOrWhiteSpace(docCommentXml))
        {
            return;
        }

        System.Xml.Linq.XElement member;
        try
        {
            member = System.Xml.Linq.XElement.Parse(docCommentXml);
        }
        catch (System.Xml.XmlException)
        {
            return;
        }

        foreach (var node in member.Nodes())
        {
            var text = node.ToString(System.Xml.Linq.SaveOptions.DisableFormatting);
            foreach (var line in text.Split('\n'))
            {
                var trimmed = line.TrimEnd('\r').Trim();
                if (trimmed.Length == 0)
                {
                    continue;
                }

                sb.Append(indent);
                sb.Append("/// ");
                sb.AppendLine(trimmed);
            }
        }
    }

    private static void Generate(
        SourceProductionContext context,
        ImmutableArray<HandlerInfo> handlers,
        ImmutableArray<BehaviorCandidate> behaviorCandidates,
        ImmutableArray<NotificationHandlerInfo> notificationHandlers,
        ImmutableArray<StreamHandlerInfo> streamHandlers,
        ImmutableArray<StreamBehaviorCandidate> streamBehaviorCandidates,
        ImmutableArray<ExceptionHandlerCandidate> exceptionHandlerCandidates,
        ImmutableArray<ExceptionActionCandidate> exceptionActionCandidates,
        ImmutableArray<PreProcessorCandidate> preProcessorCandidates,
        ImmutableArray<PostProcessorCandidate> postProcessorCandidates,
        Compilation compilation)
    {
        var behaviors = new List<BehaviorInfo>();
        var seenBehaviorTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in behaviorCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.Behavior is null || !seenBehaviorTypes.Add(candidate.Behavior.UnboundTypeFqn))
            {
                continue;
            }

            behaviors.Add(candidate.Behavior);
        }

        var exceptionHandlers = new List<ExceptionHandlerInfo>();
        var seenExceptionHandlerTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in exceptionHandlerCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.ExceptionHandler is null || !seenExceptionHandlerTypes.Add(candidate.ExceptionHandler.UnboundTypeFqn))
            {
                continue;
            }

            exceptionHandlers.Add(candidate.ExceptionHandler);
        }

        var exceptionActions = new List<ExceptionActionInfo>();
        var seenExceptionActionTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in exceptionActionCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.ExceptionAction is null || !seenExceptionActionTypes.Add(candidate.ExceptionAction.UnboundTypeFqn))
            {
                continue;
            }

            exceptionActions.Add(candidate.ExceptionAction);
        }

        var preProcessors = new List<PreProcessorInfo>();
        var seenPreProcessorTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in preProcessorCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.PreProcessor is null || !seenPreProcessorTypes.Add(candidate.PreProcessor.UnboundTypeFqn))
            {
                continue;
            }

            preProcessors.Add(candidate.PreProcessor);
        }

        var postProcessors = new List<PostProcessorInfo>();
        var seenPostProcessorTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in postProcessorCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.PostProcessor is null || !seenPostProcessorTypes.Add(candidate.PostProcessor.UnboundTypeFqn))
            {
                continue;
            }

            postProcessors.Add(candidate.PostProcessor);
        }

        var streamBehaviors = new List<StreamBehaviorInfo>();
        var seenStreamBehaviorTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in streamBehaviorCandidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            if (candidate.Behavior is null || !seenStreamBehaviorTypes.Add(candidate.Behavior.UnboundTypeFqn))
            {
                continue;
            }

            streamBehaviors.Add(candidate.Behavior);
        }

        var registrations = new Dictionary<string, string>(StringComparer.Ordinal); // fqn → lifetime method
        var dispatchMethods = Array.Empty<DispatchMethodInfo>();

        if (!handlers.IsDefaultOrEmpty)
        {
            var methods = new List<DispatchMethodInfo>();

            foreach (var handler in handlers)
            {
                registrations[handler.HandlerTypeFqn] = handler.LifetimeMethod;

                if (handler.Methods.Count == 0)
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        AD001,
                        handler.Location,
                        handler.HandlerDisplayName));
                    continue;
                }

                foreach (var method in handler.Methods)
                {
                    methods.Add(method);

                    if (method.IsAsync && !method.HasCancellationTokenParameter)
                    {
                        context.ReportDiagnostic(Diagnostic.Create(
                            AD003,
                            method.Location,
                            method.HandlerDisplayName,
                            method.CommandDisplayName));
                    }
                }
            }

            var duplicateCommands = new HashSet<string>(StringComparer.Ordinal);
            foreach (var group in methods.GroupBy(static method => method.CommandTypeFqn, StringComparer.Ordinal))
            {
                if (group.Count() <= 1)
                {
                    continue;
                }

                duplicateCommands.Add(group.Key);
                var ordered = group
                    .OrderBy(static method => method.HandlerTypeFqn, StringComparer.Ordinal)
                    .ThenBy(static method => method.MethodName, StringComparer.Ordinal)
                    .ToArray();

                var first = ordered[0];
                for (var i = 1; i < ordered.Length; i++)
                {
                    var duplicate = ordered[i];
                    context.ReportDiagnostic(Diagnostic.Create(
                        AD002,
                        duplicate.Location,
                        duplicate.CommandDisplayName,
                        first.HandlerDisplayName,
                        duplicate.HandlerDisplayName));
                }
            }

            dispatchMethods = methods
                .Where(method => !duplicateCommands.Contains(method.CommandTypeFqn))
                .OrderBy(static method => method.CommandTypeFqn, StringComparer.Ordinal)
                .ThenBy(static method => method.HandlerTypeFqn, StringComparer.Ordinal)
                .ToArray();
        }

        var notificationGroups = Array.Empty<NotificationGroup>();

        if (!notificationHandlers.IsDefaultOrEmpty)
        {
            var notificationMethods = new List<NotificationMethodInfo>();

            foreach (var handler in notificationHandlers)
            {
                registrations[handler.HandlerTypeFqn] = handler.LifetimeMethod;

                if (handler.Methods.Count == 0)
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        AD007,
                        handler.Location,
                        handler.HandlerDisplayName));
                    continue;
                }

                foreach (var method in handler.Methods)
                {
                    notificationMethods.Add(method);

                    if (!method.HasCancellationTokenParameter)
                    {
                        context.ReportDiagnostic(Diagnostic.Create(
                            AD008,
                            method.Location,
                            method.HandlerDisplayName,
                            method.NotificationDisplayName));
                    }
                }
            }

            // Unlike commands, many handlers may legitimately subscribe to the same notification
            // type — every one of them fires when PublishAsync is called, so there is no
            // "duplicate handler" diagnostic here.
            notificationGroups = notificationMethods
                .GroupBy(static method => method.NotificationTypeFqn, StringComparer.Ordinal)
                .Select(static group => new NotificationGroup(
                    group.Key,
                    group.OrderBy(static method => method.HandlerTypeFqn, StringComparer.Ordinal).ToArray(),
                    group.Any(static method => method.ParallelPublish)))
                .OrderBy(static group => group.NotificationTypeFqn, StringComparer.Ordinal)
                .ToArray();
        }

        var streamMethods = Array.Empty<StreamMethodInfo>();

        if (!streamHandlers.IsDefaultOrEmpty)
        {
            var methods = new List<StreamMethodInfo>();

            foreach (var handler in streamHandlers)
            {
                registrations[handler.HandlerTypeFqn] = handler.LifetimeMethod;

                if (handler.Methods.Count == 0)
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        AD009,
                        handler.Location,
                        handler.HandlerDisplayName));
                    continue;
                }

                foreach (var method in handler.Methods)
                {
                    methods.Add(method);

                    if (!method.HasCancellationTokenParameter)
                    {
                        context.ReportDiagnostic(Diagnostic.Create(
                            AD011,
                            method.Location,
                            method.HandlerDisplayName,
                            method.QueryDisplayName));
                    }
                }
            }

            var duplicateQueries = new HashSet<string>(StringComparer.Ordinal);
            foreach (var group in methods.GroupBy(static method => method.QueryTypeFqn, StringComparer.Ordinal))
            {
                if (group.Count() <= 1)
                {
                    continue;
                }

                duplicateQueries.Add(group.Key);
                var ordered = group
                    .OrderBy(static method => method.HandlerTypeFqn, StringComparer.Ordinal)
                    .ToArray();

                var first = ordered[0];
                for (var i = 1; i < ordered.Length; i++)
                {
                    var duplicate = ordered[i];
                    context.ReportDiagnostic(Diagnostic.Create(
                        AD010,
                        duplicate.Location,
                        duplicate.QueryDisplayName,
                        first.HandlerDisplayName,
                        duplicate.HandlerDisplayName));
                }
            }

            streamMethods = methods
                .Where(method => !duplicateQueries.Contains(method.QueryTypeFqn))
                .OrderBy(static method => method.QueryTypeFqn, StringComparer.Ordinal)
                .ThenBy(static method => method.HandlerTypeFqn, StringComparer.Ordinal)
                .ToArray();
        }

        ReportUnmatchedConstraints(context, compilation, behaviors, preProcessors, postProcessors, streamBehaviors, dispatchMethods, streamMethods);

        if (dispatchMethods.Length == 0 && notificationGroups.Length == 0 && streamMethods.Length == 0)
        {
            return;
        }

        context.AddSource("AutoDispatch.Dispatcher.g.cs", GenerateDispatcherSource(dispatchMethods, behaviors, notificationGroups, streamMethods, streamBehaviors, exceptionHandlers, exceptionActions, preProcessors, postProcessors, compilation));
        context.AddSource("AutoDispatch.Registration.g.cs", GenerateRegistrationSource(registrations, behaviors, streamBehaviors, exceptionHandlers, exceptionActions, preProcessors, postProcessors));
    }

    private static string GenerateDispatcherSource(IReadOnlyList<DispatchMethodInfo> methods, IReadOnlyList<BehaviorInfo> behaviors, IReadOnlyList<NotificationGroup> notificationGroups, IReadOnlyList<StreamMethodInfo> streamMethods, IReadOnlyList<StreamBehaviorInfo> streamBehaviors, IReadOnlyList<ExceptionHandlerInfo> exceptionHandlers, IReadOnlyList<ExceptionActionInfo> exceptionActions, IReadOnlyList<PreProcessorInfo> preProcessors, IReadOnlyList<PostProcessorInfo> postProcessors, Compilation compilation)
    {
        var allBehaviors = behaviors
            .OrderBy(static b => b.Order)
            .ThenBy(static b => b.SortFilePath, StringComparer.Ordinal)
            .ThenBy(static b => b.SortSpanStart)
            .ThenBy(static b => b.UnboundTypeFqn, StringComparer.Ordinal)
            .ToArray();

        var allStreamBehaviors = streamBehaviors
            .OrderBy(static b => b.Order)
            .ThenBy(static b => b.SortFilePath, StringComparer.Ordinal)
            .ThenBy(static b => b.SortSpanStart)
            .ThenBy(static b => b.UnboundTypeFqn, StringComparer.Ordinal)
            .ToArray();

        // Catch clauses must go most-derived-exception-type first, or the C# compiler rejects a
        // base-type catch that would make a later, more-specific catch unreachable. Handlers and
        // actions are grouped by exact exception type (one catch per distinct type, even if
        // several handlers/actions target it) so two entries for the same exception type never
        // produce a duplicate catch. Within a catch, every action always runs first (side effects
        // only, never suppress), then handlers run in order until one reports `IsHandled`.
        var exceptionMiddlewareGroups = exceptionHandlers
            .Select(static e => e.ExceptionTypeFqn)
            .Concat(exceptionActions.Select(static a => a.ExceptionTypeFqn))
            .Distinct(StringComparer.Ordinal)
            .Select(exceptionTypeFqn => new
            {
                ExceptionTypeFqn = exceptionTypeFqn,
                Depth = Math.Max(
                    exceptionHandlers.Where(e => e.ExceptionTypeFqn == exceptionTypeFqn).Select(static e => e.ExceptionDepth).DefaultIfEmpty(0).Max(),
                    exceptionActions.Where(a => a.ExceptionTypeFqn == exceptionTypeFqn).Select(static a => a.ExceptionDepth).DefaultIfEmpty(0).Max()),
                Actions = exceptionActions
                    .Where(a => a.ExceptionTypeFqn == exceptionTypeFqn)
                    .OrderBy(static a => a.Order)
                    .ThenBy(static a => a.SortFilePath, StringComparer.Ordinal)
                    .ThenBy(static a => a.SortSpanStart)
                    .ToArray(),
                Handlers = exceptionHandlers
                    .Where(e => e.ExceptionTypeFqn == exceptionTypeFqn)
                    .OrderBy(static e => e.Order)
                    .ThenBy(static e => e.SortFilePath, StringComparer.Ordinal)
                    .ThenBy(static e => e.SortSpanStart)
                    .ToArray()
            })
            .OrderByDescending(static g => g.Depth)
            .ThenBy(static g => g.ExceptionTypeFqn, StringComparer.Ordinal)
            .ToArray();
        var hasExceptionHandlers = exceptionMiddlewareGroups.Length > 0;

        var allPreProcessors = preProcessors
            .OrderBy(static p => p.Order)
            .ThenBy(static p => p.SortFilePath, StringComparer.Ordinal)
            .ThenBy(static p => p.SortSpanStart)
            .ThenBy(static p => p.UnboundTypeFqn, StringComparer.Ordinal)
            .ToArray();

        var allPostProcessors = postProcessors
            .OrderBy(static p => p.Order)
            .ThenBy(static p => p.SortFilePath, StringComparer.Ordinal)
            .ThenBy(static p => p.SortSpanStart)
            .ThenBy(static p => p.UnboundTypeFqn, StringComparer.Ordinal)
            .ToArray();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by AutoDispatch.Generator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine();
        sb.AppendLine("namespace AutoDispatch");
        sb.AppendLine("{");
        sb.AppendLine("    public interface IDispatcher");
        sb.AppendLine("    {");

        foreach (var method in methods)
        {
            AppendDocComment(sb, method.DocCommentXml, "        ");

            sb.Append("        ");
            sb.Append(GetInterfaceReturnType(method));
            sb.Append(' ');
            sb.Append(GetDispatchMethodName(method));
            sb.Append('(');
            sb.Append(method.CommandTypeFqn);
            sb.Append(" command");
            if (method.IsAsync)
            {
                sb.Append(", global::System.Threading.CancellationToken ct = default");
            }

            sb.AppendLine(");");
        }

        foreach (var group in notificationGroups)
        {
            sb.Append("        global::System.Threading.Tasks.Task PublishAsync(");
            sb.Append(group.NotificationTypeFqn);
            sb.AppendLine(" notification, global::System.Threading.CancellationToken ct = default);");
        }

        foreach (var method in streamMethods)
        {
            AppendDocComment(sb, method.DocCommentXml, "        ");
            sb.Append("        global::System.Collections.Generic.IAsyncEnumerable<");
            sb.Append(method.ResultTypeFqn);
            sb.Append("> StreamAsync(");
            sb.Append(method.QueryTypeFqn);
            sb.AppendLine(" query, global::System.Threading.CancellationToken ct = default);");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal sealed class Dispatcher : IDispatcher");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly global::System.IServiceProvider _sp;");
        sb.AppendLine();
        sb.AppendLine("        public Dispatcher(global::System.IServiceProvider sp) => _sp = sp;");
        sb.AppendLine();

        foreach (var method in methods)
        {
            // Behaviors/pre/post-processors with a constrained TCommand type parameter (e.g.
            // `where TCommand : IAudited`) only apply to commands that satisfy that constraint —
            // filtered per command here so one command's pipeline never references a behavior
            // that couldn't actually be constructed for its type.
            var sortedBehaviors = allBehaviors
                .Where(b => CommandSatisfiesConstraints(compilation, method.CommandTypeFqn, b.CommandConstraintTypeFqns))
                .ToArray();
            var hasBehaviors = sortedBehaviors.Length > 0;

            var sortedPreProcessors = allPreProcessors
                .Where(p => CommandSatisfiesConstraints(compilation, method.CommandTypeFqn, p.CommandConstraintTypeFqns))
                .ToArray();
            var hasPreProcessors = sortedPreProcessors.Length > 0;

            var sortedPostProcessors = allPostProcessors
                .Where(p => CommandSatisfiesConstraints(compilation, method.CommandTypeFqn, p.CommandConstraintTypeFqns))
                .ToArray();
            var hasPostProcessors = sortedPostProcessors.Length > 0;

            if (!method.IsAsync || (!hasBehaviors && !hasExceptionHandlers && !hasPreProcessors && !hasPostProcessors))
            {
                // Simple expression-body form (sync, or async with no behaviors/exception handlers/processors)
                AppendDocComment(sb, method.DocCommentXml, "        ");
                sb.Append("        public ");
                sb.Append(GetInterfaceReturnType(method));
                sb.Append(' ');
                sb.Append(GetDispatchMethodName(method));
                sb.Append('(');
                sb.Append(method.CommandTypeFqn);
                sb.Append(" command");
                if (method.IsAsync)
                {
                    sb.Append(", global::System.Threading.CancellationToken ct = default");
                }

                sb.AppendLine(")");
                sb.Append("            => this._sp.GetRequiredService<");
                sb.Append(method.HandlerTypeFqn);
                sb.Append(">().");
                sb.Append(method.MethodName);
                sb.Append("(command");
                if (method.IsAsync && method.HasCancellationTokenParameter)
                {
                    sb.Append(", ct");
                }

                sb.AppendLine(");");
                sb.AppendLine();
            }
            else
            {
                // Async with pipeline, exception handlers, and/or pre/post-processors
                var resultFqn = method.AsyncResultTypeFqn ?? "global::AutoDispatch.Unit";
                var pipelineType = $"global::System.Func<global::System.Threading.Tasks.Task<{resultFqn}>>";

                AppendDocComment(sb, method.DocCommentXml, "        ");

                // Pipeline execution order, outermost-first, to make the generated chain easy to reason about.
                var handlerShortName = GetShortTypeName(method.HandlerTypeFqn);
                var pipelineOrder = string.Join(" -> ", sortedBehaviors.Select(static b => GetShortTypeName(b.UnboundTypeFqn)));
                var innerStep = handlerShortName + "." + method.MethodName;
                if (hasPreProcessors || hasPostProcessors)
                {
                    var preOrder = string.Join(", ", sortedPreProcessors.Select(static p => GetShortTypeName(p.UnboundTypeFqn)));
                    var postOrder = string.Join(", ", sortedPostProcessors.Select(static p => GetShortTypeName(p.UnboundTypeFqn)));
                    innerStep = $"[{preOrder}] -> {innerStep} -> [{postOrder}]";
                }

                sb.AppendLine($"        // Pipeline: {pipelineOrder} -> {innerStep} -> {pipelineOrder}");
                if (hasExceptionHandlers)
                {
                    var exceptionOrder = string.Join(", ", exceptionMiddlewareGroups.Select(static g => GetShortTypeName(g.ExceptionTypeFqn)));
                    sb.AppendLine($"        // Exception middleware (most-derived first): {exceptionOrder}");
                }

                sb.Append("        public ");
                if (hasExceptionHandlers)
                {
                    sb.Append("async ");
                }

                sb.AppendLine($"{GetInterfaceReturnType(method)} {GetDispatchMethodName(method)}({method.CommandTypeFqn} command, global::System.Threading.CancellationToken ct = default)");
                sb.AppendLine("        {");

                if (method.AsyncResultTypeFqn != null)
                {
                    if (!hasPreProcessors && !hasPostProcessors)
                    {
                        sb.AppendLine($"            {pipelineType} pipeline = () => this._sp.GetRequiredService<{method.HandlerTypeFqn}>().{method.MethodName}(command{(method.HasCancellationTokenParameter ? ", ct" : "")});");
                    }
                    else
                    {
                        sb.AppendLine($"            {pipelineType} pipeline = async () =>");
                        sb.AppendLine("            {");
                        foreach (var p in sortedPreProcessors)
                        {
                            var preTypeFqn = p.UnboundTypeFqn.Replace("<>", $"<{method.CommandTypeFqn}>");
                            sb.AppendLine($"                await this._sp.GetRequiredService<{preTypeFqn}>().ProcessAsync(command, ct).ConfigureAwait(false);");
                        }

                        sb.AppendLine($"                var _result = await this._sp.GetRequiredService<{method.HandlerTypeFqn}>().{method.MethodName}(command{(method.HasCancellationTokenParameter ? ", ct" : "")}).ConfigureAwait(false);");
                        foreach (var p in sortedPostProcessors)
                        {
                            var postTypeFqn = p.UnboundTypeFqn.Replace("<,>", $"<{method.CommandTypeFqn}, {resultFqn}>");
                            sb.AppendLine($"                await this._sp.GetRequiredService<{postTypeFqn}>().ProcessAsync(command, _result, ct).ConfigureAwait(false);");
                        }

                        sb.AppendLine("                return _result;");
                        sb.AppendLine("            };");
                    }
                }
                else
                {
                    sb.AppendLine($"            {pipelineType} pipeline = async () =>");
                    sb.AppendLine("            {");
                    foreach (var p in sortedPreProcessors)
                    {
                        var preTypeFqn = p.UnboundTypeFqn.Replace("<>", $"<{method.CommandTypeFqn}>");
                        sb.AppendLine($"                await this._sp.GetRequiredService<{preTypeFqn}>().ProcessAsync(command, ct).ConfigureAwait(false);");
                    }

                    sb.AppendLine($"                await this._sp.GetRequiredService<{method.HandlerTypeFqn}>().{method.MethodName}(command{(method.HasCancellationTokenParameter ? ", ct" : "")}).ConfigureAwait(false);");
                    sb.AppendLine("                var _result = global::AutoDispatch.Unit.Value;");
                    foreach (var p in sortedPostProcessors)
                    {
                        var postTypeFqn = p.UnboundTypeFqn.Replace("<,>", $"<{method.CommandTypeFqn}, {resultFqn}>");
                        sb.AppendLine($"                await this._sp.GetRequiredService<{postTypeFqn}>().ProcessAsync(command, _result, ct).ConfigureAwait(false);");
                    }

                    sb.AppendLine("                return _result;");
                    sb.AppendLine("            };");
                }

                for (var i = sortedBehaviors.Length - 1; i >= 0; i--)
                {
                    var b = sortedBehaviors[i];
                    var behaviorTypeFqn = b.UnboundTypeFqn.Replace("<,>", $"<{method.CommandTypeFqn}, {resultFqn}>");
                    sb.AppendLine($"            var _b{i} = this._sp.GetRequiredService<{behaviorTypeFqn}>();");
                    sb.AppendLine($"            var _p{i} = pipeline;");
                    sb.AppendLine($"            pipeline = () => _b{i}.HandleAsync(command, _p{i}, ct);");
                }

                if (!hasExceptionHandlers)
                {
                    sb.AppendLine("            return pipeline();");
                }
                else if (method.AsyncResultTypeFqn != null)
                {
                    sb.AppendLine("            try");
                    sb.AppendLine("            {");
                    sb.AppendLine("                return await pipeline().ConfigureAwait(false);");
                    sb.AppendLine("            }");

                    var handlerIndex = 0;
                    foreach (var group in exceptionMiddlewareGroups)
                    {
                        sb.AppendLine($"            catch ({group.ExceptionTypeFqn} ex)");
                        sb.AppendLine("            {");
                        foreach (var action in group.Actions)
                        {
                            var actionTypeFqn = action.UnboundTypeFqn.Replace("<>", $"<{method.CommandTypeFqn}>");
                            sb.AppendLine($"                await this._sp.GetRequiredService<{actionTypeFqn}>().ExecuteAsync(command, ex, ct).ConfigureAwait(false);");
                        }

                        foreach (var eh in group.Handlers)
                        {
                            var ehTypeFqn = eh.UnboundTypeFqn.Replace("<,>", $"<{method.CommandTypeFqn}, {resultFqn}>");
                            sb.AppendLine($"                var _eh{handlerIndex} = this._sp.GetRequiredService<{ehTypeFqn}>();");
                            sb.AppendLine($"                var _er{handlerIndex} = await _eh{handlerIndex}.HandleAsync(command, ex, ct).ConfigureAwait(false);");
                            sb.AppendLine($"                if (_er{handlerIndex}.IsHandled) return _er{handlerIndex}.Response!;");
                            handlerIndex++;
                        }

                        sb.AppendLine("                throw;");
                        sb.AppendLine("            }");
                    }
                }
                else
                {
                    sb.AppendLine("            try");
                    sb.AppendLine("            {");
                    sb.AppendLine("                await pipeline().ConfigureAwait(false);");
                    sb.AppendLine("                return;");
                    sb.AppendLine("            }");

                    var handlerIndex = 0;
                    foreach (var group in exceptionMiddlewareGroups)
                    {
                        sb.AppendLine($"            catch ({group.ExceptionTypeFqn} ex)");
                        sb.AppendLine("            {");
                        foreach (var action in group.Actions)
                        {
                            var actionTypeFqn = action.UnboundTypeFqn.Replace("<>", $"<{method.CommandTypeFqn}>");
                            sb.AppendLine($"                await this._sp.GetRequiredService<{actionTypeFqn}>().ExecuteAsync(command, ex, ct).ConfigureAwait(false);");
                        }

                        foreach (var eh in group.Handlers)
                        {
                            var ehTypeFqn = eh.UnboundTypeFqn.Replace("<,>", $"<{method.CommandTypeFqn}, {resultFqn}>");
                            sb.AppendLine($"                var _eh{handlerIndex} = this._sp.GetRequiredService<{ehTypeFqn}>();");
                            sb.AppendLine($"                var _er{handlerIndex} = await _eh{handlerIndex}.HandleAsync(command, ex, ct).ConfigureAwait(false);");
                            sb.AppendLine($"                if (_er{handlerIndex}.IsHandled) return;");
                            handlerIndex++;
                        }

                        sb.AppendLine("                throw;");
                        sb.AppendLine("            }");
                    }
                }

                sb.AppendLine("        }");
                sb.AppendLine();
            }
        }

        foreach (var group in notificationGroups)
        {
            var handlerNames = string.Join(", ", group.Methods.Select(static m => GetShortTypeName(m.HandlerTypeFqn)));

            if (!group.ParallelPublish)
            {
                // Fan-out publish: every registered handler for this notification type runs in
                // deterministic (handler-type-name) order. A handler throwing stops the remaining
                // handlers from running, matching MediatR's default ForeachAwaitPublisher behavior.
                sb.AppendLine($"        // Publish fan-out (sequential): {handlerNames}");
                sb.AppendLine($"        public async global::System.Threading.Tasks.Task PublishAsync({group.NotificationTypeFqn} notification, global::System.Threading.CancellationToken ct = default)");
                sb.AppendLine("        {");

                foreach (var method in group.Methods)
                {
                    sb.Append("            await this._sp.GetRequiredService<");
                    sb.Append(method.HandlerTypeFqn);
                    sb.Append(">().HandleAsync(notification");
                    if (method.HasCancellationTokenParameter)
                    {
                        sb.Append(", ct");
                    }

                    sb.AppendLine(").ConfigureAwait(false);");
                }

                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else
            {
                // [ParallelPublish] fan-out: every registered handler for this notification type
                // is started immediately (via PublishTaskHelpers.SafeInvoke, which converts a
                // synchronous throw into a faulted task) and awaited together via Task.WhenAll,
                // matching MediatR's TaskWhenAllPublisher. All handlers run even if one throws;
                // failures surface as the first exception (or an AggregateException if more than
                // one handler faults and the caller inspects it directly).
                sb.AppendLine($"        // Publish fan-out (parallel via Task.WhenAll): {handlerNames}");
                sb.AppendLine($"        public global::System.Threading.Tasks.Task PublishAsync({group.NotificationTypeFqn} notification, global::System.Threading.CancellationToken ct = default)");
                sb.AppendLine("            => global::System.Threading.Tasks.Task.WhenAll(");

                for (var i = 0; i < group.Methods.Count; i++)
                {
                    var method = group.Methods[i];
                    sb.Append("                global::AutoDispatch.PublishTaskHelpers.SafeInvoke(() => this._sp.GetRequiredService<");
                    sb.Append(method.HandlerTypeFqn);
                    sb.Append(">().HandleAsync(notification");
                    if (method.HasCancellationTokenParameter)
                    {
                        sb.Append(", ct");
                    }

                    sb.Append(')');
                    sb.Append(')');
                    sb.AppendLine(i < group.Methods.Count - 1 ? "," : ");");
                }

                sb.AppendLine();
            }
        }

        foreach (var method in streamMethods)
        {
            // Streaming queries are request/response like Send — exactly one handler per query
            // type. With no [StreamBehavior]s registered, the generated method delegates
            // directly to the handler's async stream with no buffering. With one or more
            // [StreamBehavior]s, the generated method builds a lazy pipeline of nested
            // Func<IAsyncEnumerable<T>> calls, matching the command pipeline's semantics but
            // without Task-wrapping (HandleAsync returns the enumerable directly; only
            // enumerating it awaits anything).
            AppendDocComment(sb, method.DocCommentXml, "        ");

            var sortedStreamBehaviors = allStreamBehaviors
                .Where(b => CommandSatisfiesConstraints(compilation, method.QueryTypeFqn, b.QueryConstraintTypeFqns))
                .ToArray();
            var hasStreamBehaviors = sortedStreamBehaviors.Length > 0;

            if (!hasStreamBehaviors)
            {
                sb.Append("        public global::System.Collections.Generic.IAsyncEnumerable<");
                sb.Append(method.ResultTypeFqn);
                sb.Append("> StreamAsync(");
                sb.Append(method.QueryTypeFqn);
                sb.AppendLine(" query, global::System.Threading.CancellationToken ct = default)");
                sb.Append("            => this._sp.GetRequiredService<");
                sb.Append(method.HandlerTypeFqn);
                sb.Append(">().HandleAsync(query");
                if (method.HasCancellationTokenParameter)
                {
                    sb.Append(", ct");
                }

                sb.AppendLine(");");
                sb.AppendLine();
            }
            else
            {
                var handlerShortName = GetShortTypeName(method.HandlerTypeFqn);
                var pipelineOrder = string.Join(" -> ", sortedStreamBehaviors.Select(static b => GetShortTypeName(b.UnboundTypeFqn)));
                var pipelineType = $"global::System.Func<global::System.Collections.Generic.IAsyncEnumerable<{method.ResultTypeFqn}>>";

                sb.AppendLine($"        // Stream pipeline: {pipelineOrder} -> {handlerShortName}.HandleAsync");
                sb.Append("        public global::System.Collections.Generic.IAsyncEnumerable<");
                sb.Append(method.ResultTypeFqn);
                sb.Append("> StreamAsync(");
                sb.Append(method.QueryTypeFqn);
                sb.AppendLine(" query, global::System.Threading.CancellationToken ct = default)");
                sb.AppendLine("        {");
                sb.Append($"            {pipelineType} pipeline = () => this._sp.GetRequiredService<{method.HandlerTypeFqn}>().HandleAsync(query");
                sb.Append(method.HasCancellationTokenParameter ? ", ct" : string.Empty);
                sb.AppendLine(");");

                for (var i = sortedStreamBehaviors.Length - 1; i >= 0; i--)
                {
                    var b = sortedStreamBehaviors[i];
                    var behaviorTypeFqn = b.UnboundTypeFqn.Replace("<,>", $"<{method.QueryTypeFqn}, {method.ResultTypeFqn}>");
                    sb.AppendLine($"            var _sb{i} = this._sp.GetRequiredService<{behaviorTypeFqn}>();");
                    sb.AppendLine($"            var _sp{i} = pipeline;");
                    sb.AppendLine($"            pipeline = () => _sb{i}.HandleAsync(query, _sp{i}, ct);");
                }

                sb.AppendLine("            return pipeline();");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string GenerateRegistrationSource(Dictionary<string, string> registrations, IReadOnlyList<BehaviorInfo> behaviors, IReadOnlyList<StreamBehaviorInfo> streamBehaviors, IReadOnlyList<ExceptionHandlerInfo> exceptionHandlers, IReadOnlyList<ExceptionActionInfo> exceptionActions, IReadOnlyList<PreProcessorInfo> preProcessors, IReadOnlyList<PostProcessorInfo> postProcessors)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by AutoDispatch.Generator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine("namespace AutoDispatch");
        sb.AppendLine("{");
        sb.AppendLine("    public static class AutoDispatchServiceCollectionExtensions");
        sb.AppendLine("    {");
        sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddAutoDispatch(");
        sb.AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("        {");

        foreach (var kvp in registrations.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            sb.Append("            services.");
            sb.Append(kvp.Value);
            sb.Append('<');
            sb.Append(kvp.Key);
            sb.AppendLine(">();");
        }

        foreach (var behavior in behaviors.OrderBy(static b => b.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({behavior.UnboundTypeFqn}));");
        }

        foreach (var behavior in streamBehaviors.OrderBy(static b => b.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({behavior.UnboundTypeFqn}));");
        }

        foreach (var handler in exceptionHandlers.OrderBy(static e => e.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({handler.UnboundTypeFqn}));");
        }

        foreach (var action in exceptionActions.OrderBy(static a => a.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({action.UnboundTypeFqn}));");
        }

        foreach (var processor in preProcessors.OrderBy(static p => p.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({processor.UnboundTypeFqn}));");
        }

        foreach (var processor in postProcessors.OrderBy(static p => p.UnboundTypeFqn, StringComparer.Ordinal))
        {
            sb.AppendLine($"            services.AddScoped(typeof({processor.UnboundTypeFqn}));");
        }

        sb.AppendLine("            services.AddScoped<global::AutoDispatch.IDispatcher, global::AutoDispatch.Dispatcher>();");
        sb.AppendLine("            return services;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string ReadLifetimeMethod(ImmutableArray<AttributeData> attributes)
    {
        foreach (var attr in attributes)
        {
            foreach (var arg in attr.NamedArguments)
            {
                if (arg.Key == "Lifetime" && arg.Value.Value is int val)
                {
                    return val switch
                    {
                        1 => "AddSingleton",
                        2 => "AddTransient",
                        _ => "AddScoped"
                    };
                }
            }
        }
        return "AddScoped";
    }

    private static bool IsTaskLike(ITypeSymbol returnType)
    {
        if (returnType is not INamedTypeSymbol namedType)
        {
            return false;
        }

        var constructedFrom = namedType.ConstructedFrom.ToDisplayString();
        return namedType.ToDisplayString() == "System.Threading.Tasks.Task" ||
