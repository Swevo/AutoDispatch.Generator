    private static BehaviorCandidate? TransformBehavior(GeneratorAttributeSyntaxContext context, CancellationToken ct)
    {
        if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
        {
            return null;
        }

        var behaviorDisplayName = typeSymbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
        var location = typeSymbol.Locations.FirstOrDefault() ?? Location.None;

        if (typeSymbol.TypeKind != TypeKind.Class ||
            typeSymbol.DeclaredAccessibility != Accessibility.Public ||
            typeSymbol.IsAbstract ||
            typeSymbol.TypeParameters.Length != 2)
        {
            return new BehaviorCandidate
            {
                Diagnostics = ImmutableArray.Create(Diagnostic.Create(
                    AD004,
                    location,
                    behaviorDisplayName))
            };
        }

        var pipelineBehaviorType = context.SemanticModel.Compilation.GetTypeByMetadataName("AutoDispatch.IPipelineBehavior`2");
        var typeParameters = typeSymbol.TypeParameters;
        var implementsPipelineBehavior =
            pipelineBehaviorType is not null &&
            typeSymbol.AllInterfaces.Any(interfaceSymbol =>
                SymbolEqualityComparer.Default.Equals(interfaceSymbol.OriginalDefinition, pipelineBehaviorType) &&
                interfaceSymbol.TypeArguments.Length == 2 &&
                SymbolEqualityComparer.Default.Equals(interfaceSymbol.TypeArguments[0], typeParameters[0]) &&
                SymbolEqualityComparer.Default.Equals(interfaceSymbol.TypeArguments[1], typeParameters[1]));

        if (!implementsPipelineBehavior)
        {
            return new BehaviorCandidate
            {
                Diagnostics = ImmutableArray.Create(Diagnostic.Create(
                    AD005,
                    location,
                    behaviorDisplayName))
            };
        }

        if (!HasValidBehaviorHandleAsync(typeSymbol, context.SemanticModel.Compilation))
        {
            return new BehaviorCandidate
            {
                Diagnostics = ImmutableArray.Create(Diagnostic.Create(
                    AD006,
                    location,
                    behaviorDisplayName))
            };
        }

